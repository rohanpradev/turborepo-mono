import { createHash } from "node:crypto";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

type SchemaResource = { group: string; kind: string; version: string };
type SchemaSource = {
  file: string;
  url: string;
  sha256: string;
  resources: Array<SchemaResource>;
};
type SourceManifest = { schemaVersion: number; sources: Array<SchemaSource> };
type JsonRecord = Record<string, unknown>;

const isRecord = (value: unknown): value is JsonRecord =>
  value !== null && typeof value === "object" && !Array.isArray(value);

// OpenAPI nullable needs JSON Schema's explicit null type. Reject unknown fields
// on structured objects while retaining declared maps and preserved extensions.
const convertSchema = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(convertSchema);
  if (!isRecord(value)) return value;
  const converted = Object.fromEntries(
    Object.entries(value).map(([key, child]) => [key, convertSchema(child)]),
  );
  if (value.nullable === true && typeof value.type === "string") {
    converted.type = [value.type, "null"];
  }
  delete converted.nullable;
  if (
    value.type === "object" &&
    isRecord(value.properties) &&
    value.additionalProperties === undefined &&
    value["x-kubernetes-preserve-unknown-fields"] !== true
  ) {
    converted.additionalProperties = false;
  }
  return converted;
};

/** @internal Exported for deterministic generation and corruption regressions. */
export const extractKubernetesSchemas = (
  source: SchemaSource,
  yaml: string,
): Map<string, string> => {
  const digest = createHash("sha256").update(yaml).digest("hex");
  if (digest !== source.sha256) {
    throw new Error(`Checksum mismatch for schema source ${source.file}.`);
  }
  const parsed: unknown = Bun.YAML.parse(yaml);
  const documents = Array.isArray(parsed) ? parsed : [parsed];
  const outputs = new Map<string, string>();
  for (const resource of source.resources) {
    const definition = documents.find((document) => {
      if (!isRecord(document) || document.kind !== "CustomResourceDefinition")
        return false;
      const spec = document.spec;
      return (
        isRecord(spec) &&
        spec.group === resource.group &&
        isRecord(spec.names) &&
        spec.names.kind === resource.kind
      );
    });
    const spec =
      isRecord(definition) && isRecord(definition.spec) ? definition.spec : {};
    const version = Array.isArray(spec.versions)
      ? spec.versions.find(
          (candidate: unknown) =>
            isRecord(candidate) &&
            candidate.name === resource.version &&
            candidate.served === true,
        )
      : undefined;
    const schema =
      isRecord(version) && isRecord(version.schema)
        ? version.schema.openAPIV3Schema
        : undefined;
    if (!isRecord(schema)) {
      throw new Error(
        `Missing served schema for ${resource.group}/${resource.kind}/${resource.version}.`,
      );
    }
    const filename = `${resource.group}/${resource.kind.toLowerCase()}_${resource.version}.json`;
    outputs.set(
      filename,
      `${JSON.stringify(
        {
          $schema: "http://json-schema.org/draft-07/schema#",
          $comment: `Generated by scripts/generate-kubernetes-schemas.ts from ${source.url}; SHA-256 ${source.sha256}.`,
          ...(convertSchema(schema) as JsonRecord),
        },
        null,
        2,
      )}\n`,
    );
  }
  return outputs;
};

const main = async () => {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const sourceDirectoryIndex = args.indexOf("--source-dir");
  const sourceDirectory =
    sourceDirectoryIndex >= 0 ? args[sourceDirectoryIndex + 1] : undefined;
  if (sourceDirectoryIndex >= 0 && !sourceDirectory)
    throw new Error("--source-dir requires a directory.");
  const root = fileURLToPath(new URL("..", import.meta.url));
  const outputDirectory = path.join(root, "deploy/schemas");
  const manifest = (await Bun.file(
    path.join(outputDirectory, "sources.json"),
  ).json()) as SourceManifest;
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.sources))
    throw new Error("Unsupported schema source manifest.");
  let count = 0;
  for (const source of manifest.sources) {
    const yaml = sourceDirectory
      ? await Bun.file(path.join(sourceDirectory, source.file)).text()
      : await fetch(source.url, { signal: AbortSignal.timeout(30_000) }).then(
          (response) => {
            if (!response.ok)
              throw new Error(
                `Failed to download schema source ${source.file}: ${response.status}.`,
              );
            return response.text();
          },
        );
    for (const [filename, content] of extractKubernetesSchemas(source, yaml)) {
      const target = path.join(outputDirectory, filename);
      if (check) {
        if (
          !(await Bun.file(target).exists()) ||
          (await Bun.file(target).text()) !== content
        ) {
          throw new Error(`Generated schema is stale: ${filename}.`);
        }
      } else {
        await mkdir(path.dirname(target), { recursive: true });
        await Bun.write(target, content);
      }
      count += 1;
    }
  }
  console.log(
    `${check ? "Verified" : "Generated"} ${count} pinned Kubernetes custom-resource schemas.`,
  );
};

if (import.meta.main) {
  main().catch((error: unknown) => {
    console.error(
      error instanceof Error ? error.message : "Schema generation failed.",
    );
    process.exitCode = 1;
  });
}
